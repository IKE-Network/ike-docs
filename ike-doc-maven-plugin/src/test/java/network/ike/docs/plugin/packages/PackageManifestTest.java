package network.ike.docs.plugin.packages;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * {@link PackageManifest} and {@link AdocPackages} on real trees: the
 * packages a root holds, their kind by the two rules, the group directory
 * as the domain package, and the manifest's shape.
 */
class PackageManifestTest {

    static String topic(String id) {
        return ":topic-id: %s\n:topic-type: concept\n:topic-status: draft\n:topic-keywords: k\n\n[[%s]]\n= %s\n"
                .formatted(id, id, id);
    }

    static Path write(Path root, String relative, String content) throws IOException {
        Path file = root.resolve(relative);
        Files.createDirectories(file.getParent());
        Files.writeString(file, content);
        return file;
    }

    /** The lab's library after migration: two topic domains and the library's own package. */
    static Path labLibrary(Path dir) throws IOException {
        Path root = dir.resolve("src/docs/asciidoc");
        write(root, "network.ike.lab/dev/gitflow-overview.adoc", topic("dev-gitflow-overview"));
        write(root, "network.ike.lab/dev/images/flow.svg", "<svg/>");
        write(root, "network.ike.lab/arch/overview.adoc", topic("arch-overview"));
        write(root, "network.ike.lab/arch/chapters/intro.adoc", "== Intro\n");
        write(root, "network.ike.lab/lab/index.adoc", "= Preview\n\ninclude::../dev/gitflow-overview.adoc[]\n");
        write(root, "network.ike.lab/lab/images/logo.svg", "<svg/>");
        write(root, "META-INF/ike/network.ike.lab/topics/manifest.yaml", "coordinates: stale\n");
        write(root, ".asciidoctorconfig", ":adoc: target/generated-sources/adoc\n");
        return root;
    }

    @Test
    void packages_areGroupSlashDomain_withKindByIndexAndTopics(@TempDir Path dir) throws IOException {
        List<AdocPackages.Package> packages = AdocPackages.packages(labLibrary(dir), null);

        assertThat(packages).extracting(AdocPackages.Package::name)
                .containsExactly("network.ike.lab/arch", "network.ike.lab/dev", "network.ike.lab/lab");
        assertThat(packages).extracting(AdocPackages.Package::domain).containsExactly("arch", "dev", "lab");
        assertThat(packages).extracting(AdocPackages.Package::kind)
                .containsExactly(PackageKind.TOPICS, PackageKind.TOPICS, PackageKind.LIBRARY);
        assertThat(packages.get(0).files()).hasSize(2);
        assertThat(packages.get(0).topics()).hasSize(1);
        assertThat(packages.get(0).topics().get(0).file()).isEqualTo("network.ike.lab/arch/overview.adoc");
    }

    @Test
    void libraryPackageProperty_namesTheKind_evenWhereTopicsLive(@TempDir Path dir) throws IOException {
        List<AdocPackages.Package> packages = AdocPackages.packages(labLibrary(dir), "network.ike.lab/dev");

        assertThat(packages).extracting(AdocPackages.Package::kind)
                .containsExactly(PackageKind.TOPICS, PackageKind.LIBRARY, PackageKind.LIBRARY);
    }

    @Test
    void aGroupDirectoryHoldingTopics_isTheDomainPackage(@TempDir Path dir) throws IOException {
        Path root = dir.resolve("src/docs/asciidoc");
        write(root, "network.ike.kompendium.anf/determine-topic.adoc", topic("anf-determine-topic"));
        write(root, "network.ike.kompendium.anf/images/x.svg", "<svg/>");
        write(root, "network.ike.kompendium.anf/index.adoc", "= Preview\n");

        List<AdocPackages.Package> packages = AdocPackages.packages(root, null);

        assertThat(packages).hasSize(1);
        assertThat(packages.get(0).name()).isEqualTo("network.ike.kompendium.anf");
        assertThat(packages.get(0).domain()).isEqualTo("anf");
        assertThat(packages.get(0).kind()).isEqualTo(PackageKind.TOPICS);
    }

    @Test
    void manifest_recordsCoordinatesPackagesAndRegistry(@TempDir Path dir) throws IOException {
        Map<String, Object> model = PackageManifest.model(labLibrary(dir), "network.ike.lab", "topics",
                "network.ike.lab/lab");

        assertThat(PackageManifest.yaml(model)).isEqualTo("""
                # manifest.yaml, generated by idoc:manifest from the pom and the tree. Do not edit.
                coordinates: network.ike.lab:topics
                packages:
                  - name: network.ike.lab/arch
                    kind: topics
                  - name: network.ike.lab/dev
                    kind: topics
                  - name: network.ike.lab/lab
                    kind: library
                registry: META-INF/ike/network.ike.lab/topics/topic-registry.yaml
                """);
        assertThat(AdocPackages.metaDirectory("network.ike.lab", "unlv-topics"))
                .isEqualTo("META-INF/ike/network.ike.lab/unlv-topics");
    }

    @Test
    void layout_isLegacyUnlessTheyPropertySaysPackages() {
        assertThat(AdocLayout.of(null)).isEqualTo(AdocLayout.LEGACY);
        assertThat(AdocLayout.of(" ")).isEqualTo(AdocLayout.LEGACY);
        assertThat(AdocLayout.of("legacy")).isEqualTo(AdocLayout.LEGACY);
        assertThat(AdocLayout.of("packages")).isEqualTo(AdocLayout.PACKAGES);
        assertThat(AdocLayout.of(" Packages ")).isEqualTo(AdocLayout.PACKAGES);
        org.assertj.core.api.Assertions.assertThatThrownBy(() -> AdocLayout.of("flat"))
                .isInstanceOf(IllegalArgumentException.class).hasMessageContaining("ike.adoc.layout");
    }
}

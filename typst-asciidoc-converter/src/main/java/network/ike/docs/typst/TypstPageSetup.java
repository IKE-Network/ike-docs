package network.ike.docs.typst;

/**
 * The page and furniture setup every IKE Typst document starts with: paper,
 * margins with a binding side, running head (title on the verso, current
 * level-1 section on the recto), folio in the footer, fonts, paragraph and
 * heading rules, table and raw-block styling, and the helper functions the
 * converter's output calls ({@code ike-admonition}, {@code ike-koncept},
 * {@code ike-unconverted}, …).
 *
 * <p>Spike shape: one static preamble parameterised by the document title.
 * The writer library will grow this into the page model of the design
 * topic's Page terminology (folio scheme, binding gutter, section start,
 * as-of line), driven by the same concepts whether the document comes from
 * the Asciidoctor AST or from Komet's block model.
 */
public final class TypstPageSetup {

    /** The mitex import for documents with LaTeX math: 0.2.7 is the first release that compiles under Typst 0.15 (0.2.5 fails on a removed math symbol). */
    public static final String MITEX_IMPORT = "#import \"@preview/mitex:0.2.7\": *";

    private TypstPageSetup() {}

    /**
     * The preamble for a document.
     *
     * @param title     the document title as plain text (for the running head and PDF metadata)
     * @param needsMath whether to import the mitex package
     * @return Typst source ending with a blank line
     */
    public static String preamble(String title, boolean needsMath) {
        String t = TypstText.string(title == null ? "" : title);
        StringBuilder sb = new StringBuilder(4096);
        sb.append("// Generated by the IKE typst AsciiDoc converter — do not edit; edit the AsciiDoc source.\n");
        if (needsMath) {
            sb.append(MITEX_IMPORT).append('\n');
        }
        sb.append("""
                #set document(title: %s)
                #set page(
                  paper: "a4",
                  margin: (top: 22mm, bottom: 22mm, inside: 24mm, outside: 18mm),
                  header: context {
                    set text(size: 8.5pt, fill: luma(90))
                    let page-no = counter(page).get().first()
                    if page-no > 1 {
                      if calc.odd(page-no) {
                        let before = query(selector(heading.where(level: 1)).before(here()))
                        if before.len() > 0 { align(right, before.last().body) }
                      } else {
                        align(left, %s)
                      }
                    }
                  },
                  footer: context align(center, text(size: 9pt, counter(page).display("1"))),
                )
                #set text(font: ("Noto Serif", "Noto Sans"), size: 10.5pt, lang: "en", hyphenate: true)
                #set par(justify: true, leading: 0.65em, spacing: 1.1em)
                #set heading(numbering: none)
                #show heading: set text(font: "Noto Sans", weight: "bold")
                #show heading.where(level: 1): set text(size: 15pt)
                #show heading.where(level: 2): set text(size: 12.5pt)
                #show heading.where(level: 3): set text(size: 11pt)
                #show heading.where(level: 4): set text(size: 10.5pt, style: "italic")
                #show heading: it => { v(0.9em, weak: true); it; v(0.5em, weak: true) }
                #show raw: set text(font: "Noto Sans Mono", size: 0.85em)
                #show raw.where(block: true): it => block(width: 100%%, fill: luma(247), inset: 8pt, radius: 3pt, it)
                #show link: set text(fill: rgb("#1a4f8a"))
                #set table(stroke: 0.5pt + luma(150), inset: 5pt)
                #show table.cell: set par(justify: false)
                #show table.cell: set text(hyphenate: false)
                #show figure.where(kind: table): set figure.caption(position: top)
                #show figure.caption: set text(size: 9pt)
                #set figure(numbering: none)
                #set list(indent: 1em)
                #set enum(indent: 1em)
                #set terms(hanging-indent: 1.5em, separator: [: ])
                #set footnote.entry(separator: line(length: 30%%, stroke: 0.5pt))
                #show footnote.entry: set text(size: 8.5pt)

                #let ike-title(body) = block(below: 1.2em, text(font: "Noto Sans", size: 20pt, weight: "bold", body))
                #let ike-block-title(body) = block(above: 1em, below: 0.5em, text(weight: "bold", size: 0.95em, body))
                #let ike-admonition-colors = (
                  NOTE: rgb("#2a5a8a"), TIP: rgb("#3b8c2f"), IMPORTANT: rgb("#b8860b"),
                  WARNING: rgb("#c25e00"), CAUTION: rgb("#b00020"),
                )
                #let ike-admonition(kind, body) = {
                  let c = ike-admonition-colors.at(kind, default: luma(90))
                  block(width: 100%%, inset: (left: 10pt, right: 8pt, top: 6pt, bottom: 6pt),
                    stroke: (left: 2pt + c), fill: luma(248),
                    [#text(weight: "bold", size: 0.8em, fill: c, kind) \\ #body])
                }
                #let ike-example(title, body) = block(width: 100%%, inset: 8pt, stroke: 0.5pt + luma(190), radius: 2pt,
                  [#if title != none [#text(weight: "bold", size: 0.9em, title) \\ ]#body])
                #let ike-sidebar(title, body) = block(width: 100%%, inset: 8pt, fill: luma(244), radius: 2pt,
                  [#if title != none [#text(weight: "bold", size: 0.9em, title) \\ ]#body])
                #let ike-verse(body) = block(inset: (left: 1.5em), body)
                #let ike-unconverted(ctx, body) = block(width: 100%%, stroke: 1pt + rgb("#b00020"), inset: 6pt,
                  [#text(weight: "bold", size: 0.8em, fill: rgb("#b00020"))[UNCONVERTED #ctx] \\ #body])
                #let ike-unconverted-inline(ctx, body) = box(stroke: 0.5pt + rgb("#b00020"), inset: 2pt,
                  text(fill: rgb("#b00020"), size: 0.9em)[#ctx: #body])
                #let ike-xref-unresolved(id, body) = text(fill: rgb("#9a3b3b"))[#body#super[?]]
                #let ike-index(..terms) = [#metadata((index: terms.pos())) <ike-index>]
                // TODO(#1307): the badge demo in ike-docs/notes/typst-badge-demo compares the renderer's SVG
                // against a native Typst drawing with identicon; take its recommendation here. Until then a
                // Koncept is its label in a rounded box in the pill colours of KonceptAppearance.defaults().
                #let ike-koncept(label, kind: "KONCEPT", inactive: false) = box(
                  fill: if kind == "STAMP" { rgb("#ecebe8") } else { rgb("#e9eff6") },
                  radius: 0.5em, inset: (x: 0.45em, top: 0.1em, bottom: 0.1em), outset: (y: 0.12em),
                  text(fill: if kind == "STAMP" { rgb("#5a5750") } else { rgb("#2a5a8a") }, weight: 500, size: 0.92em,
                    if inactive { strike(label) } else { label }))

                """.formatted(t, t));
        return sb.toString();
    }
}
